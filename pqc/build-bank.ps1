#Requires -Version 5.1
<#
.SYNOPSIS
  Regenerates bank-data.js from pqc-questions.md + pqc-answers.md.

.DESCRIPTION
  Embeds the Markdown banks as a same-folder script so the app can start
  when opened via file:// (where fetch of .md files is blocked).
  After editing either .md file, re-run this script before relying on file://.
#>
$ErrorActionPreference = 'Stop'

$Root = $PSScriptRoot
$QuestionsPath = Join-Path $Root 'pqc-questions.md'
$AnswersPath = Join-Path $Root 'pqc-answers.md'
$OutPath = Join-Path $Root 'bank-data.js'
$MaxBytes = 5 * 1024 * 1024

if (-not (Test-Path -LiteralPath $QuestionsPath)) {
  throw "Missing questions file: $QuestionsPath"
}
if (-not (Test-Path -LiteralPath $AnswersPath)) {
  throw "Missing answers file: $AnswersPath"
}

$questions = [System.IO.File]::ReadAllText($QuestionsPath)
$answers = [System.IO.File]::ReadAllText($AnswersPath)

if ([string]::IsNullOrWhiteSpace($questions)) {
  throw 'pqc-questions.md is empty.'
}
if ([string]::IsNullOrWhiteSpace($answers)) {
  throw 'pqc-answers.md is empty.'
}
if ($questions.Length -gt $MaxBytes) {
  throw "pqc-questions.md exceeds $MaxBytes bytes."
}
if ($answers.Length -gt $MaxBytes) {
  throw "pqc-answers.md exceeds $MaxBytes bytes."
}

# JSON string literals are valid JavaScript string literals.
$qJson = ConvertTo-Json -InputObject $questions -Compress
$aJson = ConvertTo-Json -InputObject $answers -Compress
$generated = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'

$body = @"
/* Auto-generated by build-bank.ps1 — do not edit by hand.
 * Source: pqc-questions.md + pqc-answers.md
 * Generated: $generated
 */
window.PQC_EMBEDDED_BANK = Object.freeze({
  questions: $qJson,
  answers: $aJson
});
"@

$utf8NoBom = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllText($OutPath, $body, $utf8NoBom)

# Study bank uses "### Q001" and "**Correct answer:** D".
# Older banks used "1. **Q001" stems and "| Q001 | D |" key rows.
$qStudy = ([regex]::Matches($questions, '(?m)^### Q\d{3}\s*$')).Count
$qLegacy = ([regex]::Matches($questions, '(?m)^\d+\.\s+\*\*Q\d{3}\b')).Count
$qMarks = [Math]::Max($qStudy, $qLegacy)
$aStudy = ([regex]::Matches($answers, '(?m)^\*\*Correct answer:\*\*\s*[A-D]\s*$')).Count
$aLegacy = ([regex]::Matches($answers, '(?i)\|\s*Q\d{3}\s*\|\s*[A-D]\s*(?=\|)')).Count
$aKeys = [Math]::Max($aStudy, $aLegacy)

Write-Host "Wrote $OutPath"
Write-Host ("Questions: {0:N0} chars ({1} stems); Answers: {2:N0} chars ({3} key rows)" -f `
  $questions.Length, $qMarks, $answers.Length, $aKeys)
Write-Host 'Re-open index.html (file:// or local server) to pick up the new bank.'
